#!/usr/bin/env python3
"""
Rebuild personal/gallery.js from the image files in personal/.

    personal/
      photography/   <- drop photos here
      sports/        <- and here
      drawings/      <- and here (any new folder becomes its own filter)

On GitHub this runs automatically after every upload (see .github/workflows/deploy.yml).
Locally:  python3 tools/build_gallery.py

What it does
  * Finds every image under personal/ (folders starting with "_" or "." are skipped).
    JPG, PNG, WebP, GIF and AVIF always work; iPhone HEIC works when pillow-heif is
    installed (it is on GitHub).
  * Self-organizes: category = top folder; within a category, newest first by the date
    the photo was taken (EXIF), then by file name. A subfolder name, such as
    sports/volleyball/, becomes part of the caption.
  * Captions come from file names ("duke-gardens_in-fog.jpg" -> "Duke gardens in fog";
    a leading number like "03-" is dropped). Edit any caption in personal/gallery.js and
    it is kept on later runs.
  * With Pillow installed, it writes web-sized copies to personal/_web/ (900 px for the
    grid, 2000 px for the viewer) so large phone photos load fast.
"""
import json
import os
import re
import sys
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PERSONAL = os.path.join(ROOT, "personal")
WEB = os.path.join(PERSONAL, "_web")
MANIFEST = os.path.join(PERSONAL, "gallery.js")

BASE_EXT = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"}
HEIC_EXT = {".heic", ".heif"}
CONVERT_EXT = {".tif", ".tiff", ".bmp", ".dng", ".cr2", ".cr3", ".nef", ".arw", ".raw"}
CATEGORY_ORDER = ["Photography", "Sports", "Drawings"]
GRID_PX, FULL_PX = 900, 2000

HEADER = """/*
  Personal gallery. Generated by tools/build_gallery.py from the folders in personal/.
  Upload photos into personal/photography/, personal/sports/ or personal/drawings/ and
  this list rebuilds itself. You can edit "caption" and "alt" here; edits are kept.
*/
"""

try:
    from PIL import Image, ImageOps
    HAVE_PIL = True
except ImportError:
    HAVE_PIL = False
try:
    import pillow_heif  # type: ignore
    pillow_heif.register_heif_opener()
    HAVE_HEIF = HAVE_PIL
except Exception:
    HAVE_HEIF = False

OK_EXT = BASE_EXT | (HEIC_EXT if HAVE_HEIF else set())


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def words(stem):
    stem = re.sub(r"^\d+[\s._-]+", "", stem)
    stem = re.sub(r"[_\-]+", " ", stem).strip()
    return re.sub(r"\s+", " ", stem)


def caption_from_name(filename, album=""):
    w = words(os.path.splitext(filename)[0])
    if re.fullmatch(r"(img|dsc|dscn|pxl|photo|image|screenshot)\s?\d[\d\s]*", w, re.I):
        w = ""                                   # camera file names make poor captions
    w = (w[:1].upper() + w[1:]) if w else ""
    if album:
        a = words(album)
        a = a[:1].upper() + a[1:]
        return f"{a} · {w}" if w else a
    return w


def category_from_folder(folder):
    return words(folder).title() or "Personal"


def read_manifest():
    if not os.path.exists(MANIFEST):
        return []
    text = open(MANIFEST, encoding="utf-8").read()
    m = re.search(r"window\.PERSONAL_GALLERY\s*=\s*(\[.*\])\s*;?\s*$", text, re.S)
    if not m:
        sys.exit("Couldn't find `window.PERSONAL_GALLERY = [...]` in personal/gallery.js")
    try:
        data = json.loads(m.group(1))
    except json.JSONDecodeError as e:
        sys.exit(f"personal/gallery.js isn't valid JSON inside the brackets: {e}\n"
                 "Check for single quotes, trailing commas, or comments inside the list.")
    return [d for d in data if isinstance(d, dict)]


def find_sources():
    found, skipped = [], []
    for dirpath, dirnames, filenames in os.walk(PERSONAL):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith((".", "_")))
        sub = os.path.relpath(dirpath, PERSONAL)
        parts = [] if sub == "." else sub.split(os.sep)
        for name in sorted(filenames):
            if name.startswith("."):
                continue
            ext = os.path.splitext(name)[1].lower()
            path = os.path.join(dirpath, name)
            if ext in OK_EXT:
                cat = category_from_folder(parts[0]) if parts else "Personal"
                album = " ".join(parts[1:])
                found.append((path, cat, album))
            elif ext in CONVERT_EXT or ext in HEIC_EXT:
                skipped.append(rel(path))
    return found, skipped


def taken_date(im):
    try:
        exif = im.getexif()
        raw = None
        try:
            raw = exif.get_ifd(0x8769).get(36867) or exif.get_ifd(0x8769).get(36868)
        except Exception:
            pass
        raw = raw or exif.get(306)
        if raw:
            return datetime.strptime(str(raw).strip()[:19], "%Y:%m:%d %H:%M:%S")
    except Exception:
        pass
    return None


def process(src_path, category):
    """Return dict(src, full, width, height, taken) for one image."""
    info = {"src": rel(src_path)}
    if not HAVE_PIL:
        return info
    try:
        with Image.open(src_path) as im0:
            taken = taken_date(im0)
            if taken:
                info["taken"] = taken.strftime("%Y-%m-%d")
            if getattr(im0, "is_animated", False):
                info["width"], info["height"] = im0.width, im0.height
                return info
            im = ImageOps.exif_transpose(im0)
            stem = re.sub(r"[^A-Za-z0-9._-]+", "-", os.path.splitext(os.path.basename(src_path))[0])
            out_dir = os.path.join(WEB, re.sub(r"[^a-z0-9]+", "-", category.lower()))
            os.makedirs(out_dir, exist_ok=True)
            outs = {}
            for size in (GRID_PX, FULL_PX):
                out = os.path.join(out_dir, f"{stem}-{size}.webp")
                if not (os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(src_path)):
                    copy = im.copy()
                    copy.thumbnail((size, size * 3) if size == GRID_PX else (size, size), Image.LANCZOS)
                    if copy.mode not in ("RGB", "RGBA"):
                        alpha = "A" in copy.getbands() or "transparency" in copy.info
                        copy = copy.convert("RGBA" if alpha else "RGB")
                    copy.save(out, "WEBP", quality=82, method=6)
                outs[size] = out
            with Image.open(outs[GRID_PX]) as g:
                info["width"], info["height"] = g.size
            info["src"], info["full"] = rel(outs[GRID_PX]), rel(outs[FULL_PX])
    except Exception as e:
        print(f"  ! couldn't process {rel(src_path)} ({e}); using the original")
    return info


def main():
    os.makedirs(PERSONAL, exist_ok=True)
    existing = read_manifest()
    by_orig = {(e.get("orig") or e.get("src")): e for e in existing if (e.get("orig") or e.get("src"))}
    sources, skipped = find_sources()

    out, new = [], 0
    for path, cat, album in sources:
        key = rel(path)
        old = by_orig.get(key, {})
        if not old:
            new += 1
        info = process(path, cat)
        entry = {
            "src": info["src"],
            "caption": old.get("caption", caption_from_name(os.path.basename(key), album)),
            "alt": old.get("alt", ""),
            "category": old.get("category", cat),
            "orig": key,
        }
        for k in ("full", "width", "height", "taken"):
            if k in info:
                entry[k] = info[k]
        out.append(entry)

    def order(e):
        c = e["category"]
        ci = CATEGORY_ORDER.index(c) if c in CATEGORY_ORDER else len(CATEGORY_ORDER)
        # newest first: undated photos go last within their category
        t = e.get("taken") or ""
        return (ci, c, 0 if t else 1, "".join(chr(0x10FFFF - ord(ch)) for ch in t), e["orig"].lower())
    out.sort(key=order)

    # remove web copies whose original was deleted or renamed
    keep = {os.path.join(ROOT, e[k]) for e in out for k in ("src", "full") if e.get(k)}
    pruned = 0
    if os.path.isdir(WEB):
        for dirpath, _, filenames in os.walk(WEB, topdown=False):
            for name in filenames:
                fp = os.path.join(dirpath, name)
                if fp not in keep:
                    os.remove(fp); pruned += 1
            if dirpath != WEB and not os.listdir(dirpath):
                os.rmdir(dirpath)

    keys = {e["orig"] for e in out}
    removed = sum(1 for k in by_orig if k not in keys and str(k).startswith("personal/"))
    # entries pointing outside personal/ (e.g. a URL you added by hand) are kept
    external = [e for e in existing if not str(e.get("orig") or e.get("src", "")).startswith("personal/")]
    out = external + out

    with open(MANIFEST, "w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write("window.PERSONAL_GALLERY = ")
        f.write(json.dumps(out, indent=2, ensure_ascii=False))
        f.write(";\n")

    counts = {}
    for e in out:
        counts[e.get("category", "?")] = counts.get(e.get("category", "?"), 0) + 1
    print(f"personal/gallery.js: {len(out)} item(s) (+{new} new, -{removed} removed) "
          + ", ".join(f"{k}: {v}" for k, v in counts.items())
          + (f"; pruned {pruned} stale web cop{'y' if pruned == 1 else 'ies'}" if pruned else ""))
    if skipped:
        print("  Skipped (needs conversion" + ("" if HAVE_HEIF else "; pip install pillow-heif for HEIC") + "):")
        for s in skipped:
            print("   -", s)
    if not HAVE_PIL:
        print("  Tip: pip install Pillow pillow-heif, then re-run to make web-sized copies.")


if __name__ == "__main__":
    main()
